#!/usr/bin/env python3
"""atpp — check an Agentic Trust & Protection Platform (ATPP) scan claim without trusting Redthread.

A badge image is a pointer, never proof. The claim is an in-toto Statement in a DSSE envelope,
signed with Ed25519, bound to the sha256 of the exact MCP registry manifest that was scanned.
The public key is embedded below, so a hijacked domain cannot swap it.

  atpp verify <repo-dir>                    # reads <dir>/.atpp/attestation.dsse.json (+ badge.svg)
  atpp verify <namespace>/<server>          # fetches the current attestation from trust.redthreadsec.com
  atpp verify-runtime <tenant>/<agent> [--pin .atpp/workspace-key.json]   # a runtime agent claim, key pinned on first use
  atpp disputes [<namespace>/<server>]      # the signed public log of disputed scores and their outcomes
  atpp report mcp-scan|mcp-names              # the public aggregate report / search index match their signed copies
  options: --offline (signature, badge, expiry only) · --no-log · --expect <namespace>/<server>
  atpp badge  <namespace>/<server> [dir]    # verifies, then writes <dir>/.atpp/badge.svg + attestation
  atpp check-config [config.json ...] [--cyclonedx bom.json]   # every MCP server in your configs, checked (+ an AIBOM)
  atpp hook claude|cursor [--policy org.json] [--unscanned ask|deny] [--strict]   # gate MCP tool calls (preview)
  atpp gate <namespace>/<server> [--image ref@sha256:...] [--strict] [--policy org.json]   # allow (exit 0) or deny (exit 1)
  atpp profile <namespace>/<server> --policy org.json   # your policy as a ToolHive permission profile (egress, files)
  atpp manifest <YYYY-MM-DD> <out.json>     # the day's signed manifest, checked against the public log (what Sigstore co-signs)

Exit codes: 0 valid and current · 1 invalid (signature, digest or badge mismatch) · 2 valid but
expired · 3 incomplete or could not check (a required check could not run — never a pass).

Needs Python 3.9+ and `pip install cryptography`. Source and key history:
https://github.com/bl014h/atpp
"""
