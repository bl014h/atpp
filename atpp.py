_SKIP_VALUE = {"-e", "--env", "-v", "--volume", "--name", "-p", "--publish", "--network", "--mount", "--from", "--with", "-w"}


def install_key(kind, ident):
    """One normalized key per install target, shared with the scanner: npm/pypi/oci package without its
    version or tag, or url:<host> for a remote endpoint."""
    i = (ident or "").strip().lower()
    if kind == "url":
        return "url:" + (urllib.parse.urlparse(i).hostname or "") if "//" in i else None
    if kind == "npm" and i.startswith("@"):
        scope, _, rest = i.partition("/")
        i = scope + "/" + rest.split("@")[0]
    elif kind == "oci":
        i = i.split("@")[0]
        i = i.rsplit(":", 1)[0] if ":" in i.rsplit("/", 1)[-1] else i
    else:
        i = re.split(r"[=<>@\[]", i)[0]
    return f"{kind}:{i}" if i else None


def entry_key(e):
    """The install key behind one config entry (a stdio command or a remote URL), or None."""
    if e.get("url") or e.get("serverUrl"):
        return install_key("url", e.get("url") or e.get("serverUrl"))
    cmd = os.path.basename(str(e.get("command") or "")).lower()
    args = [str(x) for x in e.get("args") or []]
    if cmd in ("pnpm", "yarn") and args[:1] in (["dlx"], ["exec"]):
        cmd, args = "npx", args[1:]
    kind = {"npx": "npm", "bunx": "npm", "uvx": "pypi", "pipx": "pypi", "docker": "oci", "podman": "oci"}.get(cmd)
    if not kind:
        return None
    if cmd in ("pipx", "docker", "podman"):
        args = args[1:] if args[:1] in (["run"],) else []
    skip = False
    for x in args:
        if skip:
            skip = False
        elif x in _SKIP_VALUE:
            skip = True
        elif not x.startswith("-"):
            return install_key(kind, x)
    return None


def config_servers(paths):
    """(file, name, entry) for every MCP server in the given config files (both mcpServers and VS Code servers)."""
    out = []
    for p in paths:
        fp = os.path.expanduser(p)
        if not os.path.isfile(fp):
            continue
        try:
            d = json.load(open(fp, encoding="utf-8"))
        except Exception:
            continue
        blocks = [d.get("mcpServers"), d.get("servers"), (d.get("mcp") or {}).get("servers")]
        blocks += [pr.get("mcpServers") for pr in (d.get("projects") or {}).values() if isinstance(pr, dict)]
        for b in blocks:
            for name, e in (b or {}).items():
                if isinstance(e, dict):
                    out.append((p, name, e))
    return out


CACHE_DIR = os.path.expanduser("~/.cache/atpp")


def _cache(name, key=None, value=None, ttl=3600):
    """A small JSON cache for the hook (it runs on every MCP tool call). Read: returns the value if fresh, else
    None. Write: pass value. # ponytail: a local file the user owns; delete ~/.cache/atpp to force fresh checks."""
    path = os.path.join(CACHE_DIR, name)
    try:
        data = json.load(open(path))
    except Exception:
        data = {}
    if value is None:
        hit = data.get(key or "_")
        return hit["v"] if hit and time.time() - hit["t"] < ttl else None
    data[key or "_"] = {"t": time.time(), "v": value}
    os.makedirs(CACHE_DIR, exist_ok=True)
    tmp = path + ".tmp"
    json.dump(data, open(tmp, "w"))
    os.replace(tmp, path)
    return value


def signed_index(ttl=6 * 3600):
    """The registry index (listing, passed, total, install keys), signature-checked, cached for a few hours."""
    idx = _cache("index.json", ttl=ttl)
    if idx is None:
        idx = _cache("index.json", value=open_envelope(json.loads(_get(f"{TRUST}/mcp-names.json.dsse")), REPORT_TYPE))
    return idx


def index_by_key(index):
    by_key = {}
    for row in index.get("n") or []:
        for k in (row[3] if len(row) > 3 else []):
            by_key.setdefault(k, row)
    return by_key


def check_config(paths=None, bom=None):
    """The installer's view: for each configured server, the registry listing behind it and its signed score.
    With bom, also write a CycloneDX AIBOM of every configured MCP server to that path."""
    found = config_servers(paths or CONFIG_PATHS)
    if not found:
        return 3, ["no MCP config found — pass the file: atpp check-config path/to/mcp.json"]
    index = signed_index()
    by_key = index_by_key(index)
    lines, worst, records = [f"index       OK — signed registry index as of {index.get('as_of')}"], 0, []
    for f, name, e in found:
        k = entry_key(e)
        row = by_key.get(k) if k else None
        if not row:
            why = "local command, not from a package registry" if not k else "not in the official MCP registry: nobody has scanned it"
            lines.append(f"?  {name:24} {why}")
            worst = max(worst, 2 if k else 0)      # your own local command is not an unscanned third party
            records.append({"name": name, "entry": e, "status": "unscanned" if k else "local"})
            continue
        listing, passed, total = row[0], row[1], row[2]
        note, pins, arts = "", [], []
        try:
            st = open_envelope(fetch_envelope(listing))
            arts = st["predicate"].get("artifacts") or []
            for cid, ok, detail in st["predicate"]["checks"]:
                if cid in GATE_CHECKS and not ok:
                    label = "LISTING SWAP" if cid == "target-stable" else cid.upper()
                    note += f" · {label}: " + clean(detail, 120)
            for t, ident, ver, digest, prov in st["predicate"].get("artifacts") or []:
                pin = f"{ident}@{digest}" if t == "oci" and digest else f"{ident}@{ver}"
                pins.append(f"pin {t} {clean(pin, 160)}" + (f" · built by {clean(prov, 80)} (Sigstore provenance)" if prov else " · no build provenance")
                            + (f" · {clean(digest, 40)}" if t != "oci" and digest else ""))
        except Exception as ex:
            note = f" · detail not checked ({ex.__class__.__name__})"
        blocking = any(f" · {x}:" in note for x in ("LISTING SWAP", "ARTIFACT-RESOLVES", "BUILD-PROVENANCE", "TOOLS-STABLE"))
        mark = "!!" if blocking else ("ok" if passed == total else "~ ")
        if blocking:
            worst = max(worst, 1)
        records.append({"name": name, "entry": e, "listing": listing, "passed": passed, "total": total,
                        "artifacts": arts, "status": "blocked" if blocking else ("ok" if passed == total else "review")})
        lines.append(f"{mark} {name:24} {listing} · passed {passed}/{total}{note}")
        lines.append(f"   {'':24} {TRUST}/v/mcp/{listing}")
        lines += [f"   {'':24} {p}" for p in pins]
    lines.append("static registry scan, not a runtime claim · ok = passed every check · ~ = some checks failed, see the link · !! = do not trust by name: swapped, missing version, built elsewhere or tools changed silently · ? = unscanned")
    if bom:
        json.dump(cyclonedx(records, index.get("as_of")), open(bom, "w"), indent=1)
        lines.append(f"aibom       wrote {bom} (CycloneDX 1.6, {len(records)} MCP servers)")
    return worst, lines


def _purl(t, ident, ver, digest):
    if t == "npm":
        return "pkg:npm/" + urllib.parse.quote(ident, safe="/") + "@" + urllib.parse.quote(ver)
    if t == "pypi":
        return f"pkg:pypi/{ident.lower()}@{urllib.parse.quote(ver)}"
    if t == "oci":
        repo = ident.split("@")[0].rsplit(":", 1)[0] if ":" in ident.rsplit("/", 1)[-1] else ident.split("@")[0]
        name = repo.rsplit("/", 1)[-1]
        return f"pkg:oci/{name}@{urllib.parse.quote(digest or ver, safe='')}?repository_url={urllib.parse.quote(repo, safe='/')}"
    return None


def _hashes(t, digest):
    out = []
    for d in str(digest or "").split(";"):
        if d.startswith("sha512-"):
            out.append({"alg": "SHA-512", "content": base64.b64decode(d[7:]).hex()})
        elif d.startswith("sha256:"):
            out.append({"alg": "SHA-256", "content": d[7:]})
    return out


def cyclonedx(records, as_of=None):
    """A CycloneDX 1.6 BOM of configured MCP servers: one component per resolved package (purl, hashes, build
    provenance), one service per remote endpoint, with the signed scan status as properties."""
    import uuid
    comps, svcs = [], []
    for r in records:
        e, props = r["entry"], [{"name": "mcp:server", "value": r["name"]}, {"name": "atpp:status", "value": r["status"]}]
        if r.get("listing"):
            props += [{"name": "atpp:listing", "value": r["listing"]},
                      {"name": "atpp:score", "value": f"{r['passed']}/{r['total']}"},
                      {"name": "atpp:verify", "value": f"{TRUST}/v/mcp/{r['listing']}"}]
            if as_of:
                props.append({"name": "atpp:scanned", "value": as_of})
        url = e.get("url") or e.get("serverUrl")
        if url:
            svcs.append({"bom-ref": f"svc:{r['name']}", "name": r["name"], "endpoints": [url], "properties": props})
            continue
        arts = r.get("artifacts") or []
        if not arts:
            comps.append({"type": "application", "bom-ref": f"mcp:{r['name']}", "name": r["name"], "properties": props})
        for t, ident, ver, digest, prov in arts:
            c = {"type": "application", "bom-ref": f"mcp:{r['name']}:{ident}", "name": ident, "version": ver,
                 "purl": _purl(t, ident, ver, digest), "properties": list(props)}
            h = _hashes(t, digest)
            if h:
                c["hashes"] = h
            if prov:
                c["externalReferences"] = [{"type": "vcs", "url": f"https://github.com/{prov}" if "/" in prov and "." not in prov.split("/")[0] else prov,
                                            "comment": "repository named in the package's Sigstore build provenance"}]
            comps.append(c)
    return {"bomFormat": "CycloneDX", "specVersion": "1.6", "serialNumber": f"urn:uuid:{uuid.uuid4()}", "version": 1,
            "metadata": {"timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                         "tools": {"components": [{"type": "application", "name": "atpp", "publisher": "Redthread Security",
                                                   "externalReferences": [{"type": "vcs", "url": "https://github.com/bl014h/atpp"}]}]}},
            "components": comps, "services": svcs}


# ------------------------------------------------------------------ hooks (gate MCP tool calls in Claude Code / Cursor)
def _hook_entry(kind, ev, paths=None):
    """(server name, config entry) for the MCP server a hook event is about, or (name, None)."""
    if kind == "claude":
        parts = str(ev.get("tool_name") or "").split("__")
        if len(parts) < 3 or parts[0] != "mcp" or parts[1].startswith("plugin_"):
            return None, None
        name = parts[1]
        cfgs = (paths or CONFIG_PATHS) + [os.path.join(ev.get("cwd") or ".", ".mcp.json")]
        return name, next((e for _f, n, e in config_servers(cfgs) if n == name), None)
    name = ev.get("mcp_server_name")
    url = ev.get("url") or ev.get("mcp_server_url")
    if url:
        return name, {"url": url}
    try:
        argv = shlex.split(ev.get("command") or "")
    except ValueError:
        argv = []
    return name, ({"command": argv[0], "args": argv[1:]} if argv else None)


def hook_decision(kind, ev, policy=None, unscanned=None, strict=False, paths=None):
    """(decision, reason): decision is "deny", "ask", "allow" or None (no opinion, normal flow continues)."""
    name, entry = _hook_entry(kind, ev, paths)
    if name is None and kind == "claude":
        return None, ""
    k = entry_key(entry) if entry else None
    row = index_by_key(signed_index()).get(k) if k else None
    if not row:
        if policy is not None:
            return "deny", f"{name}: not on your MCP allow-list (no registry listing behind it)"
        if k and unscanned:
            return unscanned, f"{name} is not in the official MCP registry, so nobody has scanned it"
        return None, ""
    listing = row[0]
    image = next((a for a in (entry or {}).get("args") or [] if "@sha256:" in str(a)), None)
    ck = "|".join([listing, image or "", str(strict), json.dumps(policy, sort_keys=True) if policy else ""])
    v = _cache("verdicts.json", ck)
    if v is None:
        ok, reasons = gate(listing, image=image, strict=strict, policy=policy)
        v = _cache("verdicts.json", ck, {"ok": ok, "reasons": reasons})
    if v["ok"]:
        return ("allow" if kind == "cursor" else None), f"{listing}: " + "; ".join(v["reasons"])
    return "deny", f"ATPP gate denied {name} ({listing}): " + "; ".join(v["reasons"]) + f" — {TRUST}/v/mcp/{listing}"


def hook_output(kind, decision, reason):
    if kind == "cursor":
        return {"permission": decision or "allow", "user_message": reason, "agent_message": reason}
    if decision is None:
        return None
    return {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": decision,
                                   "permissionDecisionReason": reason}}


# ------------------------------------------------------------------ gate (allow or deny a launch)
GATE_CHECKS = ("target-stable", "artifact-resolves", "build-provenance", "tools-stable")   # failing any of these always denies


def load_policy(path):
    """Your organisation's MCP policy. The scanner never writes this: only you know what a server may reach.
    {"servers": {"<namespace>/<server>": {"image": "ref@sha256:...", "egress": ["api.github.com"],
                                          "read": ["/workspace"], "write": []}},
     "strict": false}
    A server missing from "servers" is denied when a policy is in force."""
    pol = json.load(open(path, encoding="utf-8"))
    if not isinstance(pol.get("servers"), dict):
        raise ValueError("policy needs a \"servers\" object")
    return pol


def toolhive_profile(entry):
    """A ToolHive permission profile (network allow-list, file mounts) from one policy entry."""
    return {"network": {"outbound": {"insecure_allow_all": False, "allow_host": sorted(entry.get("egress") or []),
                                     "allow_port": sorted(entry.get("ports") or [443])}},
            "read": sorted(entry.get("read") or []), "write": sorted(entry.get("write") or [])}


def gate(name, image=None, strict=False, env=None, online=True, policy=None):
    """(allowed, reasons) for launching `name`. Denies on: a claim that does not verify or has expired, a
    listing swap, a listed version that does not exist, build provenance from another repository, and an
    image whose digest is not one the scan resolved. --strict also denies anything short of every check
    passing, and an image not pinned by digest. Anything that could not be checked denies: never a pass.
    With a policy, a server not on its allow-list is denied and a pinned image must match exactly."""
    if policy is not None:
        entry = policy["servers"].get(name)
        if entry is None:
            return False, [f"{name} is not on your MCP allow-list"]
        strict = strict or bool(policy.get("strict"))
        pin = entry.get("image")
        if pin and image and image != pin:
            return False, [f"image {image} is not the one your policy pins ({pin})"]
        image = image or pin
    try:
        env = env or fetch_envelope(name)
        status, _lines = check(env, None, online=online, expect=name, log=False)
    except Exception as e:
        return False, [f"claim did not verify: {e}"]
    if status != 0:
        return False, ["claim expired or could not be fully checked"]
    pred = json.loads(base64.b64decode(env["payload"]))["predicate"]
    reasons = [f"{cid} failed: {clean(detail, 160)}" for cid, ok, detail in pred.get("checks") or []
               if not ok and (strict or cid in GATE_CHECKS)]
    if image:
        digest = image.split("@", 1)[1] if "@sha256:" in image else None
        scanned = {a[3] for a in pred.get("artifacts") or [] if a[0] == "oci" and a[3]}
        if digest and digest not in scanned:
            reasons.append(f"image digest {digest[:19]}… is not one the scan resolved ({', '.join(sorted(d[:19] + '…' for d in scanned)) or 'none'})")
        elif not digest and strict:
            reasons.append("image is not pinned by digest (ref@sha256:…), so what runs cannot be matched to what was scanned")
    return not reasons, reasons or [f"allowed — {pred['passed']}/{pred['total']} checks, as of {pred['as_of']}"]


def day_manifest(date, log_entry=None):
    """The day's signed manifest envelope as canonical bytes, after checking that it is the one committed to the
    public log and that our pinned key signed it. These bytes are what the keyless Sigstore co-signature covers."""
    entry = log_entry or json.loads(_get(f"{LOG_RAW}/{date}.json"))
    env = json.loads(_get(f"{TRUST}/v/log/{date}.json"))
    if envelope_sha256(env) != entry.get("manifest_sha256"):
        raise VerifyError(f"the served {date} manifest is not the one in the public log")
    open_envelope(env, MANIFEST_TYPE)
    return canonical(env)


def fetch_envelope(name):
    ns, _, srv = name.partition("/")
    if not ns or not srv:
        raise ValueError("expected <namespace>/<server>")
    return json.loads(_get(f"{TRUST}/v/mcp/{ns}/{srv}.json"))


def _opt(a, flag):
    if flag in a:
        i = a.index(flag)
        v = a[i + 1] if i + 1 < len(a) else None
        del a[i:i + 2]
        return v
    return None


def main(argv=None):
    a = list(sys.argv[1:] if argv is None else argv)
    online, log = "--offline" not in a, "--no-log" not in a
    a = [x for x in a if x not in ("--offline", "--no-log")]
    expect = _opt(a, "--expect")
    if a and a[0] == "verify-runtime" and len(a) >= 2:
        pin = _opt(a, "--pin")
        try:
            status, lines = check_runtime(a[1], pin)
        except VerifyError as e:
            print(f"INVALID — {e}")
            return 1
        except Exception as e:
            print(f"could not check: {e}", file=sys.stderr)
            return 3
        print("\n".join(lines))
        return status
    if a and a[0] == "disputes":
        try:
            _, lines = check_disputes(a[1] if len(a) > 1 else None)
        except VerifyError as e:
            print(f"INVALID — {e}")
            return 1
        except Exception as e:
            print(f"could not check: {e}", file=sys.stderr)
            return 3
        print("\n".join(lines))
        return 0
    if a and a[0] == "manifest" and len(a) == 3:
        try:
            body = day_manifest(a[1])
        except VerifyError as e:
            print(f"INVALID — {e}")
            return 1
        open(a[2], "wb").write(body)
        print(f"wrote {a[2]} — sha256 {hashlib.sha256(body).hexdigest()}")
        return 0
    if a and a[0] == "profile" and len(a) >= 2:
        pp = _opt(a, "--policy")
        if not pp:
            print("profile needs --policy org.json", file=sys.stderr)
            return 3
        entry = load_policy(pp)["servers"].get(a[1])
        if entry is None:
            print(f"{a[1]} is not on your MCP allow-list", file=sys.stderr)
            return 1
        print(json.dumps(toolhive_profile(entry), indent=1))
        return 0
    if a and a[0] == "gate" and len(a) >= 2:
        image, strict, pp = _opt(a, "--image"), "--strict" in a, _opt(a, "--policy")
        try:
            pol = load_policy(pp) if pp else None
        except Exception as e:
            print(f"DENY  {a[1]}\n  policy could not be read: {e}")
            return 1
        ok, reasons = gate(a[1], image=image, strict=strict, online=online, policy=pol)
        print(("ALLOW " if ok else "DENY  ") + a[1])
        print("\n".join("  " + r for r in reasons))
        return 0 if ok else 1
    if a and a[0] == "hook" and len(a) >= 2 and a[1] in ("claude", "cursor"):
        pp, uns, strict = _opt(a, "--policy"), _opt(a, "--unscanned"), "--strict" in a
        try:
            ev = json.loads(sys.stdin.read() or "{}")
            d, why = hook_decision(a[1], ev, policy=load_policy(pp) if pp else None,
                                   unscanned=uns if uns in ("ask", "deny") else None, strict=strict)
        except Exception as e:                      # a gate that cannot decide denies
            d, why = "deny", f"ATPP gate could not check this MCP server ({e.__class__.__name__}): {e}"
        out = hook_output(a[1], d, why)
        if out is not None:
            print(json.dumps(out))
        return 0
    if a and a[0] == "check-config":
        bom = _opt(a, "--cyclonedx")
        try:
            status, lines = check_config(a[1:] or None, bom=bom)
        except VerifyError as e:
            print(f"INVALID — {e}")
            return 1
        except Exception as e:
            print(f"could not check: {e}", file=sys.stderr)
            return 3
        print("\n".join(lines))
        return status
    if len(a) == 2 and a[0] == "report" and a[1] in REPORTS:
        try:
            _, lines = check_report(a[1])
        except VerifyError as e:
            print(f"INVALID — {e}")
            return 1
        except Exception as e:
            print(f"could not check: {e}", file=sys.stderr)
            return 3
        print("\n".join(lines))
        return 0
    if len(a) < 2 or a[0] not in ("verify", "badge"):
        print(__doc__.strip().split("\n\n")[1], file=sys.stderr)
        return 3
    cmd, target = a[0], a[1]
    try:
        repo = None
        if cmd == "verify" and os.path.isdir(target):
            repo, d = target, os.path.join(target, ".atpp")
            env = json.load(open(os.path.join(d, "attestation.dsse.json")))
            bp = os.path.join(d, "badge.svg")
            svg = open(bp, "rb").read() if os.path.exists(bp) else None
        else:
            env, svg = fetch_envelope(target), None
            expect = expect or target
        status, lines = check(env, svg, online=online, repo_dir=repo, expect=expect, log=log)
    except VerifyError as e:
        print(f"INVALID — {e}")
        return 1
    except Exception as e:
        print(f"could not check: {e}", file=sys.stderr)
        return 3
    print("\n".join(lines))
    if cmd == "badge":
        if status != 0:
            print("not writing a badge: the claim is expired or could not be fully checked", file=sys.stderr)
            return status
        st = json.loads(base64.b64decode(env["payload"]))
        p = st["predicate"]
        out = os.path.join(a[2] if len(a) > 2 else ".", ".atpp")
        os.makedirs(out, exist_ok=True)
        name = st["subject"][0]["name"].removeprefix("mcp:")
        svg_out = render_badge(name, p["version"], p["passed"], p["total"], p["as_of"], p["rules_version"])
        if hashlib.sha256(svg_out.encode("utf-8")).hexdigest() != p.get("badge_sha256"):
            # The claim was signed by a different badge renderer than this one; writing would produce a
            # badge that fails verification. The next daily scan re-signs with the current renderer.
            print("not writing: this claim was signed with a different badge renderer; retry after the next daily scan", file=sys.stderr)
            return 3
        open(os.path.join(out, "badge.svg"), "w", encoding="utf-8").write(svg_out)
        json.dump(env, open(os.path.join(out, "attestation.dsse.json"), "w"), indent=1)
        ns, _, srv = name.partition("/")
        print(f"\nwrote {out}/badge.svg and {out}/attestation.dsse.json — README line:\n"
              f"[![ATPP scanned {p['passed']}/{p['total']} · v{clean(p['version'], VERSION_SHOWN)} · {p['as_of']}](.atpp/badge.svg)]"
              f"({TRUST}/v/mcp/{ns}/{srv})")
    return status


